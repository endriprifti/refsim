def f(x, d=3):
    try:
        if pd.isna(x):
            return "—"
        return f"{float(x):.{d}f}"
    except (TypeError, ValueError):
        return str(x)


def table(df, cols, heads=None, fmt=None):
    heads = heads or cols
    fmt = fmt or {}
    s = "| " + " | ".join(heads) + " |\n|" + "---|" * len(cols) + "\n"
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append(f(v, fmt.get(c, 3)) if isinstance(v, (int, float)) and not isinstance(v, bool) else str(v))
        s += "| " + " | ".join(cells) + " |\n"
    return s + "\n"


def short(rule):
    rule = str(rule)
    code = rule.split(" ")[0]
    if code == "V11":
        base = rule.split("carrying ")[-1]
        return "V11 (λ 0.5) on " + short(base)
    args = rule.rsplit("(", 1)[-1].rstrip(")") if "(" in rule else ""
    args = args.replace("q=0.333333", "q=1/3").replace(", denominator=E", "").replace("denominator=E", "")
    return (code + (" " + args if "=" in args else "")).strip()


def tl(x):
    s = str(x)
    if s.startswith("locked"):
        return "L"
    if s.startswith("campaigns"):
        return "none"
    try:
        return f"{float(s):.3f}"
    except ValueError:
        return s


