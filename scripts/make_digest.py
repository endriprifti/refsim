#!/usr/bin/env python3
"""Write docs/RESULTS_DIGEST.md from the CSV outputs of a scenario (no number is typed by hand)."""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
scen = sys.argv[1] if len(sys.argv) > 1 else "baseline_2025"
OUT = os.path.join(ROOT, "outputs", scen)


def rd(name):
    return list(csv.DictReader(open(os.path.join(OUT, name + ".csv"), encoding="utf-8")))


def f(x, d=3):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return str(x)
    return f"{v:.{d}f}"


def table(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
    for r in rows:
        s += "| " + " | ".join(str(c) for c in r) + " |\n"
    return s + "\n"


