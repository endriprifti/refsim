L.append("## 4. Local referendums (T7 municipalities, T8 qarks) at fixed resident turnout t₀ = 0.580\n")
L.append(table(["Pkg", "Type", "Units", "Not locked", "Locked", "Median Pr[change]", "Median C1", "Remark 1 exceptions (2025 basis)"],
               [(x["package"], x["type"], x["units"], x["units_change_possible"], x["units_locked"], f(x["median_P_change"]),
                 f(x["median_C1"]), x["remark1_exceptions"]) for x in lo]))

# 5 menu at two cells
g = rd("menu_grid")
for tau in ("0.3", "0.4"):
    L.append(f"## 5{'a' if tau == '0.3' else 'b'}. The menu at τ = {tau}0 of E_full, t_min = 0.20, π = 0\n")
    sel = [x for x in g if x["denominator"] == "E_full" and abs(float(x["tau"]) - float(tau)) < 1e-9 and abs(float(x["t_min"]) - 0.2) < 1e-9 and float(x["pi"]) == 0]
    L.append(table(["Rule", "Regime", "μ̂", "Pr[change]", "Pr_dec", "C1", "C1′", "C1^R", "C2", "Turnout (share of E)"],
                   [(x["rule"], x["regime"], f(x["mu_hat_eq"]) if float(x["mu_hat_eq"]) < 2 else "—", f(x["P_change"]), f(x["P_dec"]),
                     f(x["C1"]), f(x["C1p"]), f(x["C1R"]), f(x["C2"]), f(x["turnout_E"])) for x in sel]))
mixed = sum(1 for x in g if x["regime"].startswith("no pure"))
L.append(f"Grid size: {len(g)} cells (19 rules × D3 × D9 × π ∈ {{0, 0.3}} × E_full/E_dom); cells with no pure equilibrium (approximate mixed, flagged): {mixed}.\n\n")

# 6 regime map summary
m = rd("regime_map_V3")
L.append("## 6. Regime A over (ρ, τ): lock boundary by register ratio (π = 0, A2, noiseless)\n")
rows = []
for tm in (0.0, 0.2, 0.35):
    for rho in (1.0, 1.5, 1.8, 1.95, 2.1, 2.2):
        cells = sorted([x for x in m if abs(float(x["t_min"]) - tm) < 1e-9 and abs(float(x["rho"]) - rho) < 1e-9], key=lambda x: float(x["tau"]))
        first = next((x["tau"] for x in cells if not x["regime"].startswith("lock")), "none (locked or outside the model up to 0.50)")
        rows.append((tm, rho, first))
L.append(table(["t_min", "ρ", "lowest τ (grid 0.01) at which the challenger campaigns"], rows))
pa = rd("regime_map_pareto")
L.append("Pareto sets on (C1, C1′, C2) among V1, V3 (1/3), V6d (1/3), V7 (0.6), V2 (0.40), t_min = 0.20, π = 0:\n\n")
L.append(table(["ρ", "τ", "Pareto set"], [(x["rho"], x["tau"], x["pareto_set"] or "— (no feasible cell)") for x in pa if float(x["rho"]) in (1.0, 1.5, 1.9, 2.2)]))

# 7 priors and Regime B
pr = rd("prior_maps")
L.append("## 7. Lock boundary by prior shape, and the T5 opposition (Proposition 30)\n")
L.append(table(["Den.", "t_min", "a_B", "τ_lock (κ recal.)", "τ_lock (κ fixed)", "T5 opposition campaigns above"],
               [(x["denominator"], x["t_min"], x["a_B"], f(x["tau_lock_recal"]), f(x["tau_lock_fixed"]), f(x["T5_opposition_campaigns_above"])) for x in pr]))

# 8 drift
d = rd("drift_lock_years")
L.append("## 8. Drift: year Regime A locks at fixed resident turnout (E_full, t_min = 0.20, A29 path from April 2025)\n")
rows = []
for t0 in (0.55, 0.6, 0.65, 0.7, 0.75, 0.8, 0.9):
    rr = {float(x["d_R"]): x for x in d if abs(float(x["t0"]) - t0) < 1e-9}
    rows.append((t0, f(rr[0.0085]["rho_lock"]), rr[0.004]["year"], rr[0.0085]["year"], rr[0.0116]["year"]))
L.append(table(["t₀", "ρ_lock", "slow (d_R 0.004)", "central (0.0085)", "fast (0.0116)"], rows))
md = rd("drift_municipal")
L.append(table(["Case", "Basis", "2025", "2027", "2030", "2035", "2040", "2045", "Remark 1 exits (years)"],
               [(x["case"], x["basis"], x["count_y0"], x["count_y2"], x["count_y5"], x["count_y10"], x["count_y15"], x["count_y20"], x["remark1_exits"]) for x in md]))
ig = rd("drift_ig")
L.append(table(["σ_lnρ", "γ_ρ", "Pr[ρ_dom ever falls to 1.7803]", "IG 5–95% years to ρ_lock(0.60)", "to ρ_lock(0.75)"],
               [(x["sigma_lnrho"], x["gamma"], f(x["Pr_rho_dom_falls_to_1_7803"], 4), x["IG_5_95_years_to_2_0158"], x["IG_5_95_years_to_2_4182"]) for x in ig]))

# 9 signatures
s = rd("signatures_C4prime")
L.append("## 9. Signature verification: C4′ (false admission, negative margins) and false rejection (positive margins)\n")
L.append(table(["Unit", "S", "v_L", "Margin", "Error type", "R0 error", "R0 lines", "F44 rule error", "F44 lines"],
               [(x["unit"], x["S"], x["v_L"], x["margin"], x.get("kind", ""), f(x.get("R0_error", ""), 4), f(x.get("R0_lines", ""), 0),
                 f(x.get("R3_error", ""), 4), f(x.get("R3_lines", ""), 0)) for x in s if x["unit"] != "bound"]))

# 10 pipeline
pl = rd("pipeline_Pr_vote")
L.append("## 10. Pipeline: valid national initiative, regular terms (exact enumeration)\n")
L.append(table(["Scenario", "President", "Verification", "Pr_vote ≤ 12 m", "≤ 24 m", "≤ 48 m", "Mean months"],
               [(x["label"].split(" (")[0], x["president"], x["verification"], f(x["Pr_vote_12"]), f(x["Pr_vote_24"]), f(x["Pr_vote_48"]), f(x["mean_months"], 1)) for x in pl]))

# 11 window, opinion, campaign
w = rd("window_compliance")
L.append("## 11. Window (Proposition 28, q_w = 0.10), bar (Proposition 25), campaign complexity (Corollary 7)\n")
L.append(table(["T_pre", "T_post", "pre ok 2021", "post ok 2021", "pre ok 2025", "post ok 2025", "anchored window blocked share"],
               [(x["T_pre"], x["T_post"], x["pre_ok_2021"], x["post_ok_2021"], x["pre_ok_2025"], x["post_ok_2025"], f(x["anchored_window_blocked_share"])) for x in w]))
ob = rd("opinion_bar")
L.append(table(["T_rel (years)", "q_χ", "fidelity horizon (years)", "3-year bar exceeds it"],
               [(x["T_rel_years"], f(x["q_chi"]), f(x["fidelity_horizon_years"], 2), x["bar_exceeds"]) for x in ob]))
ck = [x for x in rd("campaign_L_k") if float(x["pi"]) == 0 and abs(float(x["t_min"]) - 0.2) < 1e-9]
L.append(table(["Den.", "L (days)", "β_I", "k at which change becomes infeasible", "A_I(k = 10)"],
               [(x["denominator"], x["L_days"], x["beta_I"], x["k_min_infeasible"], f(x["A_I_k10"])) for x in ck]))

# 12 convergence
cv = rd("convergence")
L.append("## 12. Monte Carlo against exact quadrature (20,000 replications per cell)\n")
L.append(f"{len(cv)} cells; largest deviation {max(float(x['max_z']) for x in cv):.2f} Monte Carlo standard errors; "
         f"largest difference between the n/2 and n runs {max(float(x['max_half_diff']) for x in cv):.4f}.\n")


# 13-19: v1.0.1 additions
u = rd("packages_uncertainty")
L.append("## 13. Draws: minimum, maximum and number of locked draws (60 common draws)\n")
L.append(table(["Pkg", "Type", "n", "locked", "Pr[change] min–max", "C1′ min–max", "C1^R mean [2.5, 97.5]"],
               [(x["package"], x["type"], x["n"], x["n_locked"], f"{f(x.get('P_change_min',''))}–{f(x.get('P_change_max',''))}",
                 f"{f(x.get('C1p_min',''),4)}–{f(x.get('C1p_max',''),4)}",
                 f"{f(x.get('C1R_mean',''))} [{f(x.get('C1R_lo95',''))}, {f(x.get('C1R_hi95',''))}]") for x in u]))
pp = rd("packages_paired")
L.append("## 14. Paired differences against P0 on common draws (package minus P0)\n")
L.append(table(["Pkg", "Type", "Criterion", "mean", "2.5–97.5%", "min–max", "share > 0", "share < 0"],
               [(x["package"], x["type"], x["criterion"], f(x["mean_diff_vs_P0"]), f"[{f(x['lo95'])}, {f(x['hi95'])}]",
                 f"{f(x['min'])}–{f(x['max'])}", f(x["share_positive"], 2), f(x["share_negative"], 2))
                for x in pp if x["type"] in ("T1", "T5")]))
sg = rd("sensitivity_sigma_tau")
L.append("## 15. Turnout-noise sweep (E_full, t_min = 0.20, π = 0; strategies from the noiseless game, A31)\n")
L.append(table(["σ_τ", "Rule", "τ", "Regime", "Pr[change]", "C1", "C1′", "C1^R", "C2"],
               [(x["sigma_tau"], x["rule"].split(" (")[0], x["tau"], x["regime"], f(x["P_change"]), f(x["C1"]), f(x["C1p"]), f(x["C1R"]), f(x["C2"])) for x in sg]))
pn = rd("regime_map_pareto_noisy")
import collections
cnt = collections.Counter(x["pareto_set"] or "— (no feasible cell)" for x in pn)
L.append("## 16. Pareto sets with noise (σ_τ = 0.04) against the noiseless map\n")
L.append("Noiseless map (regime_map_pareto.csv): V1 in every feasible cell; V6d (one third of R) joins V1 by a tie in the slack region Z1 in "
         + str(sum(1 for x in rd("regime_map_pareto") if "V6d" in x["pareto_set"])) + " cells (resident turnout ρτ ≥ 0.822 at t_min = 0.20).\n\n")
L.append(table(["Pareto set with noise", "cells"], sorted(cnt.items(), key=lambda kv: -kv[1])))
w4 = rd("t4_w4")
L.append("## 17. T4: share of adoption weekdays with a feasible polling Sunday (Proposition 23)\n")
L.append(table(["d_rev (days)", "lead 30 days", "lead 42 days"], [(x["d_rev_days"], f(x["w4_lead_30_days"]), f(x["w4_lead_42_days"])) for x in w4 if int(x["d_rev_days"]) in (12, 13, 18, 19, 24, 25, 26, 27, 28, 29, 30, 31, 45, 60)]))
lit = rd("T7_literal_national_register")
L.append("## 18. T7 under the literal national-register reading (D4 boundary case)\n")
L.append(f"Bar one third of E_full against each municipality's resident adults: minimum {min(float(x['Q_literal']) for x in lit):.2f} times the residents; "
         f"feasible at full turnout in {sum(x['feasible_at_full_turnout'] == 'True' for x in lit)} of {len(lit)} municipalities.\n\n")
if os.path.exists(os.path.join(OUT, "T8_literal_national_register.csv")):
    lq = rd("T8_literal_national_register")
    mq = min(lq, key=lambda x: float(x["Q_literal"]))
    L.append(f"T8 (v1.0.2): bar one third of E_full against each qark's resident adults: minimum {float(mq['Q_literal']):.2f} times the residents ({mq['unit']}); "
             f"feasible at full turnout in {sum(x['feasible_at_full_turnout'] == 'True' for x in lq)} of {len(lq)} qarks.\n\n")
gx = [x for x in rd("menu_grid") if x["regime"].startswith("no pure")]
ex = sorted(float(x["exploitability"]) for x in gx)
L.append("## 19. Approximate mixed equilibria and the April 2026 draft's lock boundaries\n")
L.append(f"{len(gx)} grid cells without a pure equilibrium; exploitability (largest unilateral gain, units of the stake) median {ex[len(ex)//2]:.6f}, maximum {ex[-1]:.6f}.\n\n")
dl = rd("draft_lock_boundaries")
L.append(table(["Rule", "t_min", "lowest τ at which the challenger campaigns"], [(x["rule"], x["t_min"], f(x["lock_boundary_tau"])) for x in dl]))

# 20-21: v1.0.2 additions (from existing CSV files; no new computation)
mg = rd("menu_grid")


def short(rule):
    """Rule code and name, plus the parameter group when there is one (so that V8 at two bars stays two rows)."""
    name = rule.split(" (")[0]
    last = rule.rsplit(" (", 1)[-1].rstrip(")") if rule.endswith(")") else ""
    return name + (f" ({last})" if "=" in last and last not in name else "")


L.append("## 20. The menu by bloc alignment π (menu_grid.csv; agenda setter's bloc share μ_b = 1/2)\n")
L.append("Central cell: τ = 0.30 of E_full, t_min = 0.20, A2 on the support [π/2, 1 − π/2], σ_τ = 0.04. Each pair is π = 0 / π = 0.3.\n\n")
cc = [x for x in mg if x["denominator"] == "E_full" and float(x["tau"]) == 0.30 and float(x["t_min"]) == 0.20]
by = collections.defaultdict(dict)
for x in cc:
    by[x["rule"]][float(x["pi"])] = x
rows = []
for rule in sorted(by, key=lambda r: (r.split(" ")[0][:1], int(''.join(ch for ch in r.split(" ")[0][1:] if ch.isdigit()) or 0), r)):
    a, b = by[rule].get(0.0), by[rule].get(0.3)
    if a is None or b is None:
        continue
    rows.append((short(rule), f"{a['regime']} / {b['regime']}",
                 *[f"{f(a[k])} / {f(b[k])}" for k in ("P_change", "C1", "C1p", "C1R", "C2")]))
L.append(table(["Rule", "Regime", "Pr[change]", "C1", "C1′", "C1^R", "C2"], rows))
L.append("Regime A (V3 at one third of E, E_full) by τ, t_min and π (regime at π = 0 / π = 0.3):\n\n")
v3 = [x for x in mg if x["code"] == "V3" and "0.333333" in x["rule"] and x["denominator"] == "E_full"]
cells = collections.defaultdict(dict)
for x in v3:
    cells[(float(x["t_min"]), float(x["tau"]))][float(x["pi"])] = "lock" if x["regime"].startswith("lock") else ("capped" if "capped" in x["regime"] else "interior")
taus = sorted({k[1] for k in cells})
L.append(table(["t_min"] + [f"τ = {t:.2f}" for t in taus],
               [(f"{tm:.2f}", *[f"{cells[(tm, t)][0.0]} / {cells[(tm, t)][0.3]}" for t in taus]) for tm in sorted({k[0] for k in cells})]))
diffs = collections.defaultdict(list)
for x in mg:
    diffs[(x["rule"], x["denominator"], x["tau"], x["t_min"])].append(x)
moved = collections.Counter()
total = collections.Counter()
for (rule, *_), xs in diffs.items():
    if len(xs) != 2:
        continue
    d0 = [x for x in xs if float(x["pi"]) == 0.0][0]
    d3 = [x for x in xs if float(x["pi"]) == 0.3][0]
    total[rule] += 1
    if abs(float(d3["P_change"]) - float(d0["P_change"])) > 0.01:
        moved[rule] += 1
L.append("Share of grid cells (τ × t_min × denominator) in which Pr[change] moves by more than 0.01 between π = 0 and π = 0.3:\n\n")
L.append(table(["Rule", "share of cells"], [(short(r), f(moved[r] / total[r], 2)) for r in sorted(total, key=lambda r: (r.split(" ")[0][:1], int(''.join(ch for ch in r.split(" ")[0][1:] if ch.isdigit()) or 0), r))]))

lu = rd("local_units")
L.append("## 21. Local units, unit by unit (local_units.csv; t₀,u = 0.580, unit registers as denominator, 2025-basis proxies) — for Appendix D\n")
L.append("ρ̂_u = Ê_u/R̂_u; 'bar > residents' marks q_A·ρ̂_u > 1 (current law infeasible even at full resident turnout); entries are Pr[change], with L for a locked unit.\n\n")
idx = collections.defaultdict(dict)
meta = {}
for x in lu:
    idx[(x["level"], x["unit"])][x["package"]] = x
    meta[(x["level"], x["unit"])] = x


def pc(x):
    if x is None:
        return "—"
    return "L" if x["regime"].startswith("lock") else f(x["P_change"])


for level, lab in (("municipality", "T7, municipalities"), ("qark", "T8, qarks")):
    units = sorted([k for k in idx if k[0] == level], key=lambda k: -float(meta[k]["rho_u"]))
    L.append(f"{lab} (sorted by ρ̂_u):\n\n")
    L.append(table(["Unit", "Ê_u", "R̂_u", "ρ̂_u", "bar > residents", "P0", "P1", "P1b", "P2"],
                   [(k[1], f(meta[k]["E_u"], 0), f(meta[k]["R_u"], 0), f(meta[k]["rho_u"]),
                     "yes" if idx[k]["P0"]["infeasible_bar"] == "True" else "",
                     pc(idx[k].get("P0")), pc(idx[k].get("P1")), pc(idx[k].get("P1b")), pc(idx[k].get("P2"))) for k in units]))

open(os.path.join(ROOT, "docs", "RESULTS_DIGEST.md"), "w", encoding="utf-8").write("\n".join(L))
print("wrote docs/RESULTS_DIGEST.md")
