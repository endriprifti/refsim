def rd(name):
    return pd.read_csv(os.path.join(OUT, name + ".csv"))


def f(x, d=3):
    try:
        if pd.isna(x):
            return "—"
        return f"{float(x):.{d}f}"
    except (TypeError, ValueError):
        return str(x)


def table(df, cols, heads=None, fmt=None):
    heads = heads or cols
    fmt = fmt or {}
    s = "| " + " | ".join(heads) + " |\n|" + "---|" * len(cols) + "\n"
    for _, r in df.iterrows():
        s += "| " + " | ".join(f(r[c], fmt.get(c, 3)) if isinstance(r[c], (int, float)) else str(r[c]) for c in cols) + " |\n"
    return s + "\n"


def short(rule):
    out = rule.split(" (")[0].split(" ")[0] + (" " + rule.rsplit("(", 1)[-1].rstrip(")") if "=" in rule.rsplit("(", 1)[-1] else "")
    return out.replace("q=0.333333, denominator=E", "q=1/3").replace(", denominator=E", "")


